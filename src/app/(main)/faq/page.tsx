export default function FaqPage() {
  const [activeCategory, setActiveCategory] = useState(FAQ_DATA[0].category);
  const [openItems, setOpenItems] = useState<Set<string>>(new Set());

  const toggle = (key: string) => {
    setOpenItems((prev) => {
      const next = new Set(prev);
      if (next.has(key)) next.delete(key);
      else next.add(key);
      return next;
    });
  };

  const currentFaq = FAQ_DATA.find((f) => f.category === activeCategory);

  return (
    <div className="max-w-3xl mx-auto space-y-6">
      <h1 className="text-xl font-bold">자주 묻는 질문</h1>

      {/* 카테고리 탭 */}
      <div className="flex gap-2 flex-wrap">
        {FAQ_DATA.map((f) => (
          <button
            key={f.category}
            onClick={() => setActiveCategory(f.category)}
            className={`px-4 py-2 rounded-lg text-sm font-medium transition-colors ${
              activeCategory === f.category
                ? "bg-primary text-white"
                : "bg-dark-card text-gray-400 hover:text-white"
            }`}
          >
            {f.category}
          </button>
        ))}
      </div>

      {/* 아코디언 */}
      <div className="space-y-2">
        {currentFaq?.items.map((item, i) => {
          const key = `${activeCategory}-${i}`;
          const isOpen = openItems.has(key);

          return (
            <div
              key={key}
              className="card p-0 overflow-hidden"
            >
              <button
                onClick={() => toggle(key)}
                className="w-full flex items-center justify-between px-5 py-4 text-left hover:bg-dark-surface/50 transition-colors"
              >
                <span className="text-sm font-medium text-gray-200 pr-4">
                  {item.q}
                </span>
                <svg
                  className={`w-5 h-5 text-gray-500 shrink-0 transition-transform duration-200 ${
                    isOpen ? "rotate-180" : ""
                  }`}
                  fill="none"
                  viewBox="0 0 24 24"
                  stroke="currentColor"
                >
                  <path
                    strokeLinecap="round"
                    strokeLinejoin="round"
                    strokeWidth={2}
                    d="M19 9l-7 7-7-7"
                  />
                </svg>
              </button>
              {isOpen && (
                <div className="px-5 pb-4 border-t border-dark-border">
                  <p className="text-sm text-gray-400 leading-relaxed pt-3">
                    {item.a}
                  </p>
                </div>
              )}
            </div>
          );
        })}
      </div>
    </div>
  );
}
